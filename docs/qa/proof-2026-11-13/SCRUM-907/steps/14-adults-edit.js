S.phase = '9: on party 2 the manager changes the mirrored Calamari (x2 -> x3) and removes the mirrored Hummus; the adults\' list follows';
const till = S.pages.mgr.page;
await S.unlock('mgr');
await S.openParty(till, S.p2, S.P2);
const r = {};
r.pageBefore = await S.cardText(till, 'Kitchen plan');
await S.tallShot(till, '09a-party2-kitchen-card-before.png', S.cardOf(till, 'Kitchen plan'));
await till.getByRole('button', { name: 'Edit party', exact: true }).first().click();
await till.getByRole('heading', { name: 'Edit party', exact: true }).waitFor({ timeout: 30000 });
const kc = S.cardOf(till, 'Kitchen plan');
await kc.getByRole('button', { name: /Add item/ }).first().waitFor({ timeout: 30000 });
await till.waitForTimeout(1500);
r.formOpened = { values: await kc.locator('input').evaluateAll(els => els.map(e => e.value).filter(Boolean)), calamariSteppers: await kc.getByRole('button', { name: 'Add one Calamari quantity', exact: true }).count(), hummusRemoves: await kc.getByRole('button', { name: 'Remove Hummus item', exact: true }).count() };
await kc.getByRole('button', { name: 'Add one Calamari quantity', exact: true }).click();
await kc.getByRole('button', { name: 'Remove Hummus item', exact: true }).click();
await till.waitForTimeout(400);
await S.tallShot(till, '09b-party2-edit-form-before-save.png', kc);
await S.unlock('mgr');
const resp = till.waitForResponse(x => /\/api\/parties\/[^/]+\/kitchen-plan$/.test(new URL(x.url()).pathname) && x.request().method() === 'PUT', { timeout: 120000 });
await till.getByRole('button', { name: 'Save changes', exact: true }).click();
const x = await resp;
const xb = await x.json().catch(() => null);
r.put = { status: x.status(), request: x.request().postDataJSON()?.changes ?? null, error: xb?.error ?? null };
await till.waitForTimeout(1200);
r.toast = await till.locator('li[data-state="open"], [role="status"]').evaluateAll(els => els.map(e => e.innerText.replace(/\s+/g, ' ').trim()).filter(t => t && !/out of stock/.test(t)));
await till.waitForTimeout(4000);
r.pageAfter = await S.cardText(till, 'Kitchen plan');
await S.tallShot(till, '09c-party2-kitchen-card-after-save.png', S.cardOf(till, 'Kitchen plan'));
const back = (await S.appCall('GET', `/events/${S.p2}/beo`)).body;
const show = l => `${l.itemName} x${l.quantity}${l.productCode ? ' [' + l.productCode + ']' : ''}${l.notes ? ' note ' + l.notes : ''}`;
r.beo = { adultsDiffer: back?.kitchenPlan?.menus?.adultsDiffer ?? null, kids: (back?.kitchenPlan?.menus?.kids ?? []).map(show), adults: (back?.kitchenPlan?.menus?.adults ?? []).map(show) };
r.till = (await S.tillRead(S.p2, 'p2-after-edit')).kitchenPlan.lines;
const logs = await S.appCall('GET', `/activity-logs?branchId=${S.APP_FLORESTA}&search=${encodeURIComponent('ZZ TEST 907 adults')}&limit=5&offset=0`);
r.activity = (logs.body?.logs ?? []).map(l => S.flat(l.description ?? ''));
// the BEO editor's Adults tab
const page = S.app.page;
S.inPlace = p => [];
await S.openBeo(S.p2);
await S.openSection('accordion-kitchen-plan');
await page.getByTestId('button-menu-tab-adults').click().catch(() => {});
await page.waitForTimeout(800);
r.beoAdultsTab = await page.evaluate(() => [...document.querySelectorAll('[data-testid^="menu-item-adults-"]')].filter(x => /^menu-item-adults-\d+$/.test(x.getAttribute('data-testid'))).map(x => (x.innerText || '').replace(/\s+/g, ' ').trim()));
await S.appShot('09d-beo-party2-adults-menu.png', 'accordion-kitchen-plan', 'start');
await page.getByTestId('button-menu-tab-kids').click().catch(() => {});
await page.waitForTimeout(800);
r.beoKidsTab = await page.evaluate(() => [...document.querySelectorAll('[data-testid^="menu-item-kids-"]')].filter(x => /^menu-item-kids-\d+$/.test(x.getAttribute('data-testid'))).map(x => (x.innerText || '').replace(/\s+/g, ' ').trim()));
await S.appShot('09e-beo-party2-kids-menu.png', 'accordion-kitchen-plan', 'start');
S.receipt.reads.p9edit = r;
return r;
