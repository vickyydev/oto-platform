import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import type { StationSessionDocument } from '@oto/shared';
vi.mock('react', () => import('./support/hooks'));
const mock = vi.hoisted(() => ({ lease: vi.fn(), renew: vi.fn(), session: vi.fn(), publish: vi.fn(), release: vi.fn(), watch: vi.fn(), get: vi.fn() }));
vi.mock('@/api/bridge', () => ({ bridgeApi: mock, watchBridgeSnapshots: mock.watch }));
vi.mock('@/api/client', async () => ({ ...await vi.importActual('@/api/client'), api: { get: mock.get } }));
vi.mock('@/lib/lane', () => ({ currentLane: () => 'platform', isBoxLaneTrigger: () => false }));
import { useTicketDisplay, type TicketDisplayState } from '@/lib/displaySession';
import { renderHook } from './support/hooks';
import { settle } from './support/fixtures';
let doc: StationSessionDocument;
let stream: { onSnapshot: (doc: StationSessionDocument) => void; onState: (value: boolean) => void };
const state = (): TicketDisplayState => ({ stage: 'identify', step: 1, sessionKey: 'visitor', tier: 'tourist', phone: '', nickname: '', contactChannel: 'whatsapp', member: null, online: true });
beforeEach(() => {
  vi.useFakeTimers(); vi.clearAllMocks();
  doc = { stationId: 'station', boxId: 'box', schemaVersion: 1, sequence: 0, stage: 'identify', language: 'en', lease: null, takeoverCount: 0, updatedAt: new Date().toISOString() };
  mock.get.mockResolvedValue({ displays: [{ id: 'display', name: 'ZZ TEST', connected: true }] });
  mock.lease.mockResolvedValue({ lease: { leaseId: 'lease' }, document: doc });
  mock.session.mockImplementation(async () => ({ document: doc }));
  mock.renew.mockImplementation(async () => ({ document: doc }));
  mock.publish.mockImplementation(async (_station, intent) => { doc = { ...doc, ...intent.payload, sequence: doc.sequence + 1 }; return { document: doc }; });
  mock.release.mockResolvedValue({ released: true });
  mock.watch.mockImplementation((_station, handlers) => { stream = handlers; return vi.fn(); });
});
afterEach(() => vi.useRealTimers());
it('publishes changed presentation within 50ms without waiting for the 1500ms safety tick', async () => {
  const hook = renderHook((value: TicketDisplayState) => useTicketDisplay('station', value, vi.fn()), state());
  await settle(); expect(mock.publish).toHaveBeenCalledOnce();
  hook.rerender({ ...state(), nickname: 'ZZ TEST changed' });
  await vi.advanceTimersByTimeAsync(50);
  expect(mock.publish).toHaveBeenCalledTimes(2);
  expect(mock.publish.mock.calls[1]![1].payload.prompt.nickname).toBe('ZZ TEST changed');
  hook.unmount();
});
it('consumes the existing staff snapshot answer immediately and only once', async () => {
  const answer = vi.fn();
  const hook = renderHook(() => useTicketDisplay('station', state(), answer));
  await settle();
  const requestId = mock.publish.mock.calls[0]![1].payload.prompt.requestId;
  stream.onState(true);
  const message = { ...doc, sequence: doc.sequence + 1, prompt: { ...doc.prompt, requestId, answer: { type: 'identify', actionId: 'answer', phone: '0000000000' } } };
  stream.onSnapshot(message);
  await vi.advanceTimersByTimeAsync(50);
  expect(answer).toHaveBeenCalledOnce();
  stream.onSnapshot(message);
  await vi.advanceTimersByTimeAsync(50);
  expect(answer).toHaveBeenCalledOnce();
  hook.unmount();
});
it('polls at 500ms when a display is connected and the staff stream is unavailable', async () => {
  const hook = renderHook(() => useTicketDisplay('station', state(), vi.fn()));
  await settle();
  await vi.advanceTimersByTimeAsync(500);
  expect(mock.session).toHaveBeenCalledOnce();
  mock.get.mockResolvedValue({ displays: [] });
  await vi.advanceTimersByTimeAsync(1_000);
  const count = mock.session.mock.calls.length;
  await vi.advanceTimersByTimeAsync(1_000);
  expect(mock.session).toHaveBeenCalledTimes(count);
  hook.unmount();
});
